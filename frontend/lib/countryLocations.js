/**
 * Projects lat/lng into SVG coordinates (viewBox 0 0 1000 500)
 * Uses Equirectangular / Miller-style cylindrical projection
 */
export function projectCoordinates(lat, lng, width = 1000, height = 500) {
  // Clamp lat between -85 and 85
  const clampedLat = Math.max(-85, Math.min(85, lat));
  const x = ((lng + 180) / 360) * width;
  const y = ((90 - clampedLat) / 180) * height;
  return { x: Math.round(x * 10) / 10, y: Math.round(y * 10) / 10 };
}

